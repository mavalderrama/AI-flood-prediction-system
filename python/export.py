"""Export the selected model to C headers and golden test vectors.

Generates (all marked GENERATED, do not edit by hand):
  Vivado/HLS/model_params.h          sizes, feature table, normalization, Q8.24 weights, threshold
  Vivado/HLS/tanh_lut.h              4096-entry tanh table (Q8.24)
  Vivado/HLS/golden_vectors.h        Q8.24 inputs -> expected Q8.24 output (HLS testbench, host tests)
  Zynq7K/Software/tests/xtopann_hw_sim.h   simulated AXI-Lite register map for host tests
  data/processed/golden_replay.csv   daily raw inputs of the test period -> expected output/alarm

Usage:  python python/export.py [--flood-stage 30] [--horizon 5]
"""
from __future__ import annotations

import argparse
import json

import numpy as np
import pandas as pd

import config
import dataset
import fixedpoint as fp

GENERATED = "// GENERATED by python/export.py -- do not edit by hand.\n"


# --------------------------------------------------------------------------- reference feature pipeline
def features_reference(rows: np.ndarray, mean: np.ndarray, std: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Loop implementation mirroring Zynq7K/Software/features.cpp exactly.

    rows: (T, N_COLS) raw daily inputs in dataset.INPUT_COLUMNS order (NaN = missing).
    Returns (x_raw (T, N_IN) int64, ok (T,) bool).
    """
    hist = dataset.history_days()
    col_idx = {c: i for i, c in enumerate(dataset.INPUT_COLUMNS)}
    n_in = len(dataset.FEATURES)
    x_raw = np.zeros((len(rows), n_in), dtype=np.int64)
    ok = np.zeros(len(rows), dtype=bool)
    for t in range(hist - 1, len(rows)):
        f = np.empty(n_in)
        for i, feat in enumerate(dataset.FEATURES):
            c = col_idx[feat.column]
            if feat.kind == "level":
                v = rows[t, c]
            elif feat.kind == "delta":
                v = rows[t, c] - rows[t - feat.param, c]
            else:  # sum, oldest to newest
                v = 0.0
                for k in range(t - feat.param + 1, t + 1):
                    v += rows[k, c]
            f[i] = v
        if np.isnan(f).any():
            continue
        z = np.clip((f - mean) / std, fp.INPUT_MIN, fp.INPUT_MAX)
        x_raw[t] = fp.to_raw(z)
        ok[t] = True
    return x_raw, ok


# --------------------------------------------------------------------------- golden vectors
def tie_vectors(q: fp.QuantizedMLP, rng: np.random.Generator, per_neuron: int = 16) -> np.ndarray:
    """Inputs whose hidden pre-activation is exactly halfway between two Q8.24 values,
    so the testbench exercises round-half-even (AP_RND_CONV)."""
    out = []
    mod = 1 << fp.FRAC_BITS
    W = q.W1
    for j in range(W.shape[0]):
        odd = [i for i in range(W.shape[1]) if W[j, i] % 2 != 0]
        if not odd:
            continue
        i = odd[0]
        inv = pow(int(W[j, i]) % mod, -1, mod)
        for _ in range(per_neuron):
            x = rng.integers(-(1 << 26), 1 << 26, size=W.shape[1]).astype(np.int64)
            x[i] = 0
            rest = int(np.sum(W[j] * x))
            x[i] = ((1 << (fp.FRAC_BITS - 1)) - rest) * inv % mod
            acc = int(np.sum(W[j] * x)) + (int(q.b1[j]) << fp.FRAC_BITS)
            assert acc % mod == 1 << (fp.FRAC_BITS - 1)
            out.append(x)
    return np.array(out, dtype=np.int64)


def edge_vectors(n_in: int, rng: np.random.Generator) -> np.ndarray:
    lo, hi = fp.to_raw(fp.INPUT_MIN), fp.to_raw(fp.INPUT_MAX)
    v = [np.full(n_in, lo), np.full(n_in, hi), np.zeros(n_in, dtype=np.int64),
         np.full(n_in, fp.ONE), np.full(n_in, -fp.ONE)]
    v += list(rng.integers(lo, hi + 1, size=(500, n_in)))
    return np.array(v, dtype=np.int64)


# --------------------------------------------------------------------------- C emitters
def c_array(ctype: str, name: str, values, per_line: int = 8, comments=None) -> str:
    vals = [str(int(v)) if ctype.startswith("int") else repr(float(v)) for v in values]
    lines = []
    for k in range(0, len(vals), per_line):
        chunk = ", ".join(vals[k:k + per_line])
        c = f"  // {comments[k // per_line]}" if comments else ""
        lines.append(f"    {chunk},{c}")
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


def write_model_params(path, m, q, horizon, flood_stage, thr_raw):
    feats = dataset.FEATURES
    n_in, h_hid = len(feats), len(m["b1"])
    col_idx = {c: i for i, c in enumerate(dataset.INPUT_COLUMNS)}
    w1_comments = [f"hidden {j}: " + ", ".join(f"{v:+.6f}" for v in m["W1"][j]) for j in range(h_hid)]
    txt = GENERATED + f"""// Flood forecaster: stage at Baton Rouge > {flood_stage:g} ft within the next {horizon} day(s).
// Number format: Q8.24 raw int32 (value = raw / 2^24).
#ifndef MODEL_PARAMS_H
#define MODEL_PARAMS_H

#include <stdint.h>

#define N_IN {n_in}
#define H_HID {h_hid}
#define HORIZON_DAYS {horizon}
#define FLOOD_STAGE_FT {flood_stage!r}
#define HISTORY_ROWS {dataset.history_days()}
// Alarm when output_raw > DECISION_THRESHOLD_RAW  (= {fp.from_raw(thr_raw):.8f})
#define DECISION_THRESHOLD_RAW {int(thr_raw)}

// Daily input row, column order:
//   {", ".join(f"{i}={c}" for i, c in enumerate(dataset.INPUT_COLUMNS))}
#define N_COLS {len(dataset.INPUT_COLUMNS)}
static const char* const INPUT_COLUMN_NAMES[N_COLS] = {{{", ".join(f'"{c}"' for c in dataset.INPUT_COLUMNS)}}};

// Feature table (see python/dataset.py FEATURES):
""" + "".join(f"//   {i}: {f.name:<16} {f.kind:<5} col={f.column} param={f.param}\n" for i, f in enumerate(feats)) + """
enum { FEAT_LEVEL = 0, FEAT_DELTA = 1, FEAT_SUM = 2 };
""" + c_array("int", "FEAT_KIND", [dataset.FEATURE_KINDS[f.kind] for f in feats]) \
        + c_array("int", "FEAT_COL", [col_idx[f.column] for f in feats]) \
        + c_array("int", "FEAT_PARAM", [f.param for f in feats]) \
        + "\n// Normalization (training split statistics): z = (x - mean) / std\n" \
        + c_array("double", "FEAT_MEAN", m["norm_mean"], per_line=4) \
        + c_array("double", "FEAT_STD", m["norm_std"], per_line=4) \
        + "\n// Weights, Q8.24. W1 is row-major [H_HID][N_IN].\n" \
        + c_array("int32_t", "W1_RAW", q.W1.ravel(), per_line=n_in, comments=w1_comments) \
        + c_array("int32_t", "B1_RAW", q.b1) \
        + c_array("int32_t", "W2_RAW", q.W2.ravel()) \
        + f"static const int32_t B2_RAW = {int(q.b2[0])};\n\n#endif\n"
    path.write_text(txt)


def write_lut(path):
    txt = GENERATED + f"""// tanh look-up table: entry i = tanh(-8 + (i + 0.5) / 256) in Q8.24 (round half even).
// Index for a Q8.24 pre-activation z: clamp((z_raw + (8 << 24)) >> 16, 0, 4095).
#ifndef TANH_LUT_H
#define TANH_LUT_H
#include <stdint.h>
""" + c_array("int32_t", "TANH_LUT_RAW", fp.TANH_LUT) + "#endif\n"
    path.write_text(txt)


def write_golden_header(path, X, Y, Z):
    rows = ",\n".join("    {" + ", ".join(str(int(v)) for v in x) + "}" for x in X)
    txt = GENERATED + f"""// Golden vectors: Q8.24 inputs and the bit-exact expected Q8.24 output.
#ifndef GOLDEN_VECTORS_H
#define GOLDEN_VECTORS_H
#include <stdint.h>
#include "model_params.h"
#define GOLDEN_N {len(X)}
static const int32_t GOLDEN_X_RAW[GOLDEN_N][N_IN] = {{
{rows}
}};
""" + c_array("int32_t", "GOLDEN_Y_RAW", Y) + f"""// Hidden-layer pre-activations (before tanh): checks the AP_RND_CONV rounding,
// which the tanh table would otherwise hide.
static const int32_t GOLDEN_Z_RAW[GOLDEN_N][H_HID] = {{
""" + ",\n".join("    {" + ", ".join(str(int(v)) for v in z) + "}" for z in Z) + "\n};\n#endif\n"
    path.write_text(txt)


def write_sim_register_map(path, n_in, h_hid):
    """A plausible HLS-style AXI-Lite map with Vivado HLS 2017.4 macro names.
    Only used by host tests; the real map comes from run_hls.tcl."""
    lines = [GENERATED, "// SIMULATED register map for host tests (Vivado HLS 2017.4 naming, bundle CTRL).",
             "// The board build uses the real xtopann_hw.h copied by Vivado/HLS/run_hls.tcl.",
             "#ifndef XTOPANN_HW_SIM_H", "#define XTOPANN_HW_SIM_H",
             "#define XTOPANN_CTRL_ADDR_AP_CTRL 0x000", "#define XTOPANN_CTRL_ADDR_GIE 0x004",
             "#define XTOPANN_CTRL_ADDR_IER 0x008", "#define XTOPANN_CTRL_ADDR_ISR 0x00c",
             "#define XTOPANN_CTRL_ADDR_B2_V_DATA 0x010", "#define XTOPANN_CTRL_BITS_B2_V_DATA 32",
             "#define XTOPANN_CTRL_ADDR_RESULT_V_DATA 0x018", "#define XTOPANN_CTRL_BITS_RESULT_V_DATA 32",
             "#define XTOPANN_CTRL_ADDR_RESULT_V_CTRL 0x01c"]
    addr = 0x20
    for name, depth in (("INPUTS_V", n_in), ("W1_V", n_in * h_hid), ("B1_V", h_hid), ("W2_V", h_hid)):
        span = 4 * (1 << int(np.ceil(np.log2(depth))))
        addr = (addr + span - 1) // span * span
        lines += [f"#define XTOPANN_CTRL_ADDR_{name}_BASE 0x{addr:03x}",
                  f"#define XTOPANN_CTRL_ADDR_{name}_HIGH 0x{addr + span - 1:03x}",
                  f"#define XTOPANN_CTRL_WIDTH_{name} 32", f"#define XTOPANN_CTRL_DEPTH_{name} {depth}"]
        addr += span
    lines += [f"#define XTOPANN_SIM_MAP_SIZE 0x{addr:03x}", "#endif", ""]
    path.write_text("\n".join(lines))


# --------------------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--flood-stage", type=float, default=config.FLOOD_STAGE_FT)
    ap.add_argument("--horizon", type=int, default=5)
    args = ap.parse_args()

    runs = json.loads((config.REPORTS / f"models_{args.flood_stage:g}ft.json").read_text())
    run = next(r for r in runs if r["horizon"] == args.horizon)
    m = run["model"]
    assert m["features"] == [f.name for f in dataset.FEATURES], "feature table changed since training"
    q = fp.QuantizedMLP(np.array(m["W1"]), np.array(m["b1"]), np.array(m["W2"]), m["b2"])
    thr_raw = int(fp.to_raw(m["threshold"]))
    mean, std = np.array(m["norm_mean"]), np.array(m["norm_std"])

    # Golden replay over the test period (raw daily inputs -> expected output).
    df = dataset.load_processed()
    test = df.loc[pd.Timestamp(dataset.Split().val_end) + pd.Timedelta(days=1) - pd.Timedelta(days=dataset.history_days() - 1):]
    rows = test[dataset.INPUT_COLUMNS].to_numpy()
    x_raw, ok = features_reference(rows, mean, std)
    y_raw = np.zeros(len(rows), dtype=np.int64)
    y_raw[ok] = q.forward_raw(x_raw[ok])
    replay = pd.DataFrame({"date": test.index.strftime("%Y-%m-%d")})
    for i, c in enumerate(dataset.INPUT_COLUMNS):
        replay[c] = [repr(float(v)) if not np.isnan(v) else "nan" for v in rows[:, i]]
    replay["expected_raw"] = np.where(ok, y_raw.astype(str), "NA")
    replay["expected_alarm"] = np.where(ok, (y_raw > thr_raw).astype(int).astype(str), "NA")
    replay.to_csv(config.DATA_PROCESSED / "golden_replay.csv", index=False)

    # Sanity: the loop features agree with the pandas features used in training.
    norm_pd = np.clip((dataset.make_features(test).to_numpy() - mean) / std, fp.INPUT_MIN, fp.INPUT_MAX)
    diff = np.abs(fp.from_raw(x_raw[ok]) - norm_pd[ok])
    assert diff.max() < 1e-6, f"reference features diverge from training features ({diff.max()})"

    rng = np.random.default_rng(2018)
    X = np.vstack([x_raw[ok], edge_vectors(len(dataset.FEATURES), rng), tie_vectors(q, rng)])
    Y = q.forward_raw(X)
    Z = q.hidden_preactivation_raw(X)

    write_model_params(config.HLS_DIR / "model_params.h", m, q, args.horizon, args.flood_stage, thr_raw)
    write_lut(config.HLS_DIR / "tanh_lut.h")
    write_golden_header(config.HLS_DIR / "golden_vectors.h", X, Y, Z)
    (config.ZYNQ_SW_DIR / "tests").mkdir(exist_ok=True)
    write_sim_register_map(config.ZYNQ_SW_DIR / "tests" / "xtopann_hw_sim.h", len(dataset.FEATURES), len(m["b1"]))

    print(f"model: H={args.horizon}d, flood stage {args.flood_stage:g} ft, N_IN={len(dataset.FEATURES)}, "
          f"H_HID={len(m['b1'])}, threshold raw={thr_raw}")
    print(f"golden vectors: {len(X)} ({int(ok.sum())} test days, {len(X) - int(ok.sum())} edge/tie cases)")
    print(f"golden replay: {len(rows)} days, {int(ok.sum())} with output, {int(((y_raw > thr_raw) & ok).sum())} alarms")


if __name__ == "__main__":
    main()
